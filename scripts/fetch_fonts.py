#!/usr/bin/env python3
"""Download Cairo + Tajawal (arabic + latin subsets) from the Google Fonts
CSS and emit self-hosted @font-face CSS so the app never depends on a remote
font CDN (which WKWebView blocks under the capacitor:// origin and which
fails offline). Files are written to public/fonts/ and the generated CSS to
src/fonts.css.
"""
import os
import re
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, "public/fonts")
CSS_OUT = os.path.join(ROOT, "src/generated-fonts.css")
os.makedirs(OUT_DIR, exist_ok=True)

UA = ("Mozilla/5.0 (iPhone; CPU iPhone OS 17_0 like Mac OS X) "
      "AppleWebKit/605.1.15 (KHTML, like Gecko) Version/17.0 "
      "Mobile/15E148 Safari/604.1")
API = ("https://fonts.googleapis.com/css2?"
       "family=Cairo:wght@400;700;800;900&"
       "family=Tajawal:wght@400;500;700;800;900&display=swap")

# Only ship the subsets we actually need (keeps bundle lean).
WANT_SUBSETS = {"arabic", "latin"}


def fetch(url, binary=False):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req) as r:
        return r.read() if binary else r.read().decode("utf-8")


def main():
    css = fetch(API)
    # Split into @font-face blocks, each preceded by a /* subset */ comment.
    parts = re.split(r"/\*\s*([a-z-]+)\s*\*/", css)
    # parts = ['', subset1, block1, subset2, block2, ...]
    faces = []
    downloaded = {}
    for i in range(1, len(parts) - 1, 2):
        subset = parts[i].strip()
        block = parts[i + 1]
        if subset not in WANT_SUBSETS:
            continue
        fam = re.search(r"font-family:\s*'([^']+)'", block)
        wght = re.search(r"font-weight:\s*(\d+)", block)
        style = re.search(r"font-style:\s*(\w+)", block)
        url = re.search(r"url\((https://[^)]+\.woff2)\)", block)
        urange = re.search(r"unicode-range:\s*([^;]+);", block)
        if not (fam and wght and url):
            continue
        family = fam.group(1)
        weight = wght.group(1)
        fstyle = style.group(1) if style else "normal"
        woff2_url = url.group(1)
        fname = f"{family}-{weight}-{subset}.woff2".replace(" ", "")
        fpath = os.path.join(OUT_DIR, fname)
        if woff2_url not in downloaded:
            data = fetch(woff2_url, binary=True)
            with open(fpath, "wb") as f:
                f.write(data)
            downloaded[woff2_url] = (fname, len(data))
            print(f"  downloaded {fname} ({len(data)//1024} KB)")
        ur = f"\n  unicode-range: {urange.group(1).strip()};" if urange else ""
        faces.append(
            "@font-face {{\n"
            "  font-family: '{family}';\n"
            "  font-style: {style};\n"
            "  font-weight: {weight};\n"
            "  font-display: swap;\n"
            "  src: url(fonts/{fname}) format('woff2');{ur}\n"
            "}}".format(family=family, style=fstyle, weight=weight,
                        fname=fname, ur=ur)
        )

    header = ("/* Self-hosted Arabic UI fonts (Cairo + Tajawal).\n"
              "   Generated by scripts/fetch_fonts.py — do not edit by hand.\n"
              "   Bundled so Arabic renders offline and under the iOS\n"
              "   capacitor:// WebView origin (no Google Fonts CDN). */\n")
    with open(CSS_OUT, "w", encoding="utf-8") as f:
        f.write(header + "\n".join(faces) + "\n")
    print(f"wrote {CSS_OUT} ({len(faces)} @font-face rules)")
    total = sum(sz for _, sz in downloaded.values())
    print(f"total font payload: {total//1024} KB across {len(downloaded)} files")


if __name__ == "__main__":
    main()
